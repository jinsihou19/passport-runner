"""Generate/check the LVGL font subset used on the Passport LCD."""

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UI = [
    ROOT / "main/runner/passport_manager.c",
    ROOT / "main/apps/esp-claw/passport_ui.c",
    ROOT / "main/apps/pomodoro/passport_pomodoro.c",
]
OUTPUT = ROOT / "assets/fonts/passport_cjk_16.c"
ASCII = range(0x20, 0x7F)


def characters():
    return sorted({ord(char) for path in UI for char in path.read_text(encoding="utf-8") if ord(char) > 0x7F})


def check(source, expected_pixels=None):
    offsets = re.search(r"unicode_offsets\[\] = \{([^}]+)\}", source).group(1)
    starts = re.findall(r"\.range_start = (\d+)", source)
    codepoints = [int(starts[-1]) + int(offset) for offset in re.findall(r"\d+", offsets)]
    if codepoints != characters():
        raise ValueError("CJK subset differs from the UI strings; regenerate the font")

    blob = re.search(r"glyph_bitmap\[\] = \{([^}]+)\}", source).group(1)
    bitmap = bytes(int(value, 16) for value in re.findall(r"0x([a-f0-9]{2})", blob))
    glyphs = re.findall(r"\.bitmap_index = (\d+), \.adv_w = \d+, \.box_w = (\d+), \.box_h = (\d+)", source)
    count = len(ASCII) + len(codepoints)
    if len(glyphs) != count:
        raise ValueError("Font cmap and glyph descriptor counts differ")
    offset = 0
    for index, descriptor in enumerate(glyphs):
        start, width, height = map(int, descriptor)
        length = (width * height + 1) // 2
        if start != offset or start + length > len(bitmap):
            raise ValueError(f"Invalid glyph bitmap range at descriptor {index + 1}")
        if expected_pixels is not None:
            pixels = [part for byte in bitmap[start:start + length] for part in (byte >> 4, byte & 15)]
            if pixels[:width * height] != expected_pixels[index]:
                raise ValueError(f"Bitmap round-trip failed at descriptor {index + 1}")
        offset += length
    if offset != len(bitmap):
        raise ValueError("Unused glyph bitmap data")
    print(f"Passport LCD font: {count} mapped glyphs ({len(codepoints)} CJK), {len(bitmap)} bitmap bytes")


def generate(path):
    from fontTools.ttLib import TTFont
    from PIL import Image, ImageDraw, ImageFont

    cjk = characters()
    codes = [*ASCII, *cjk]
    with TTFont(path) as source:
        cmap = source.getBestCmap()
        missing = [f"U+{code:04X}" for code in codes if code not in cmap]
        if missing:
            raise ValueError("Missing in source font: " + ", ".join(missing))
        copyright_text = source["name"].getDebugName(0)

    font = ImageFont.truetype(path, 16, layout_engine=ImageFont.Layout.BASIC)
    bitmap = bytearray()
    expected_pixels = []
    descriptors = ["    {0},"]
    above = below = 0
    for code in codes:
        char = chr(code)
        left, top, right, bottom = font.getbbox(char, anchor="ls")
        width, height = right - left, bottom - top
        above, below = max(above, -top), max(below, bottom)
        advance = round(font.getlength(char) * 16)
        descriptors.append(
            f"    {{.bitmap_index = {len(bitmap)}, .adv_w = {advance}, .box_w = {width}, .box_h = {height}, "
            f".ofs_x = {left}, .ofs_y = {-bottom}}},"
        )
        pixels = []
        if width and height:
            glyph = Image.new("L", (width, height))
            ImageDraw.Draw(glyph).text((-left, -top), char, font=font, fill=255, anchor="ls")
            pixels = [(value * 15 + 127) // 255 for value in glyph.tobytes()]
            if not any(pixels) and not char.isspace():
                raise ValueError(f"Blank glyph for U+{code:04X}")
        expected_pixels.append(pixels.copy())
        if len(pixels) % 2:
            pixels.append(0)
        bitmap.extend((pixels[index] << 4) | pixels[index + 1] for index in range(0, len(pixels), 2))

    bitmap_lines = "\n".join(
        "    " + ", ".join(f"0x{value:02x}" for value in bitmap[start:start + 16]) + ","
        for start in range(0, len(bitmap), 16)
    )
    offsets = ", ".join(str(code - cjk[0]) for code in cjk)
    descriptor_lines = "\n".join(descriptors)
    source = f"""/* Generated by tools/generate_passport_font.py.
 * Source: Noto Sans CJK SC Regular, Sans2.004.
 * {copyright_text}
 * SPDX-License-Identifier: OFL-1.1
 */
#include "lvgl.h"

static const uint8_t glyph_bitmap[] = {{
{bitmap_lines}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{descriptor_lines}
}};

static const uint16_t unicode_offsets[] = {{{offsets}}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start = {ASCII.start}, .range_length = {len(ASCII)}, .glyph_id_start = 1,
      .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}},
    {{.range_start = {cjk[0]}, .range_length = {cjk[-1] - cjk[0] + 1}, .glyph_id_start = {len(ASCII) + 1},
      .unicode_list = unicode_offsets, .list_length = {len(cjk)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}},
}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .cmap_num = 2,
    .bpp = 4,
    .bitmap_format = LV_FONT_FMT_TXT_PLAIN,
}};

const lv_font_t passport_cjk_16 = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {above + below + 2},
    .base_line = {below + 1},
    .dsc = &font_dsc,
}};
"""
    check(source, expected_pixels)
    OUTPUT.write_text(source, encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--font", type=Path)
    args = parser.parse_args()
    if args.check:
        check(OUTPUT.read_text(encoding="utf-8"))
    else:
        generate(args.font)
